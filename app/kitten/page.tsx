import type { Metadata } from 'next';

export const metadata: Metadata = {
  title: 'Мяугочи — котёнок в GAME',
  description: 'Живой котёнок: кормить, мыть, играть, лечить. Магазин, мини-игры, переводчик мяу, день и ночь.',
};

/**
 * Мяугочи открывается в рамке, а не переносится в React.
 *
 * Игра — самодостаточное приложение на двести с лишним килобайт: пять таблиц
 * стилей, семь скриптов, своё состояние, свой цикл времени и свои экраны.
 * Переписывать её на компоненты значило бы месяц работы и риск потерять
 * половину поведения по дороге, не получив ничего взамен: она не общается с
 * ядром и ничего от сайта не хочет.
 *
 * Рамка ещё и защищает. У игры свои глобальные стили и обработчики на всё
 * окно — попади они на общую страницу, поехали бы чужие режимы.
 */
export default function KittenPage() {
  return (
    <iframe
      src="/meowgotchi/index.html"
      title="Мяугочи"
      className="fixed inset-0 h-full w-full border-0 bg-[#ffe7f3]"
      // Скриптам игры сюда нужен доступ к своему localStorage — иначе котёнок
      // забывал бы имя и голод при каждом заходе.
      sandbox="allow-scripts allow-same-origin allow-popups allow-modals"
      allow="autoplay"
    />
  );
}
