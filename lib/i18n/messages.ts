export const UI_CATALOG_LOCALES = [
  "en",
  "ru",
  "es",
  "pt",
  "fr",
  "de",
  "ar",
  "hi",
  "zh",
  "ja",
  "ko",
  "id",
  "tr",
  "uk",
  "pl",
] as const;

type UiCatalogLocale = (typeof UI_CATALOG_LOCALES)[number];

const catalogs: Record<UiCatalogLocale, Catalog> = {
  en: englishMessages,
  ru,
  es,
  pt,
  fr,
  de,
  ar,
  hi,
  zh,
  ja,
  ko,
  id,
  tr,
  uk,
  pl,
};

function baseLocale(locale: string): string {
  return locale.trim().toLowerCase().replace("_", "-").split("-")[0] || "en";
}

export function hasUiCatalog(locale: string): boolean {
  return Object.prototype.hasOwnProperty.call(catalogs, baseLocale(locale));
}

export function getMessage(
  locale: string,
  key: MessageKey,
  params?: MessageParams,
): string {
  const base = baseLocale(locale);
  const catalog = hasUiCatalog(base)
    ? catalogs[base as UiCatalogLocale]
    : catalogs.en;
  // Фолбэк берём напрямую из английского объекта, а не из catalogs.en: только он
  // гарантированно полный, и человек на любом языке увидит английскую строку
  // вместо пустоты.
  const message = catalog[key] ?? englishMessages[key];

  if (!params) return message;

  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? placeholder : String(value);
  });
}
